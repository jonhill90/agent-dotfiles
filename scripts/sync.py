    def compiled_root_source_findings(self, path: Path) -> list[str]:
        """Duplicate or foreign `apm:source` blocks in a compiled root
        file (#14).

        `<!-- apm:source:NAME --> ... <!-- /apm:source -->` is the marker
        convention apm's *legacy* Copilot surface uses for
        `copilot-instructions.md` -- a different convention entirely from
        the single `<!-- Generated by APM CLI -->` line the other root
        files carry (checked via APM_MARKER elsewhere). A file using
        neither, or exactly one block naming the current local package,
        is fine. Anything else is exactly the #11 incident: apm's cache
        accumulating content from every local package ever registered.
        """
        if not path.is_file():
            return []
        text = path.read_text(encoding="utf-8")
        names = SOURCE_BLOCK_RE.findall(text)
        if not names:
            return []
        expected = f"_local/{self.repo.name}"
        findings: list[str] = []
        if len(names) != 1:
            findings.append(f"{len(names)} apm:source blocks (expected 1)")
        foreign = sorted({name for name in names if name != expected})
        if foreign:
            findings.append(f"foreign source block(s): {', '.join(foreign)}")
        return findings

